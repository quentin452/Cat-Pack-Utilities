OUTPUT_MD = None

IMPORT_RE = re.compile(r'^\s*import\s+((?:net\.minecraft\w*|net\.minecraftforge|cpw\.mods\.fml)[\w.]+)\s*;')
# Inline FQN references (the "MC-free by FQN" pattern): fully-qualified vanilla/FML usages in CODE, which carry
# the exact same coupling as an import line but were invisible to the import-line scan (and to the gradle import
# ratchet). Counted separately, comments stripped first, import lines excluded.
FQN_RE = re.compile(r'\b((?:net\.minecraft\w*|net\.minecraftforge|cpw\.mods\.fml)(?:\.\w+)+)')
BLOCK_COMMENT_RE = re.compile(r'/\*.*?\*/', re.S)


def class_of(fqn):
    """Trim a matched dotted chain to its CLASS: keep segments up to and including the first Uppercase one
    (net.minecraft.entity.EntityList.createEntityByName -> net.minecraft.entity.EntityList). A chain with no
    uppercase segment (a bare package prefix) is returned whole — vns_group buckets it the same way."""
    out = []
    for part in fqn.split('.'):
        out.append(part)
        if part[:1].isupper():
            break
    return '.'.join(out)

GENERATED_NOTE = (
    "> Auto-generated by `Cat-Pack-Utilities/vanilla_import_map.py` from a static scan of "
    "`src/main/java` — do NOT hand-edit. Re-run `python3 vanilla_import_map.py --repo <this-repo>` after any "
    "change to the vanilla/FML import surface (owning a subsystem, porting a symbol to a MC-free twin, adding "
    "adapter code). `--check` gates the release preflight; it is the live twin of `import-budgets.txt`. "
    "Counts BOTH `import` lines AND inline FQN references (the \"MC-free by FQN\" pattern carries the same "
    "coupling — v2 2026-07-24; the gradle import ratchet still counts import lines only, see docs/104 §2.2)."
)

